const get = async (url: string): Promise<string> => {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} ${url}`)
  return res.text()
}

const write = (path: string, text: string) => {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
}

const versions: string[] = [
  "# Bundled definitions",
  "",
  "Generated by `scripts/fetch-bundle.ts`. Do not edit the files under `proto/` by hand.",
  "",
  "| Origin | Repository | Ref | Licence | Files |",
  "|---|---|---|---|---|",
]

for (const src of sources) {
  const base = `https://raw.githubusercontent.com/${src.repo}/${src.ref}`
  for (const [from, to] of src.files) {
    write(join(ROOT, "proto", to), await get(`${base}/${from}`))
    console.log(`${src.name}: ${to}`)
  }
  write(join(ROOT, "LICENSES", `${src.name}.txt`), await get(`${base}/${src.licenceFile}`))
  versions.push(`| ${src.name} | ${src.repo} | ${src.ref} | ${src.licence} | ${src.files.length} |`)
}

write(join(ROOT, "VERSIONS.md"), `${versions.join("\n")}\n`)
