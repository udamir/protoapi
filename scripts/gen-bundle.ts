// Generates src/bundle/core-sources.ts (descriptor.proto and the language feature files, kept by protoapi/core) and
// src/bundle/sources.ts (every bundled file, reusing the core strings) from bundle/proto/**/*.proto (run after
// `bun run bundle:fetch`), and
// src/bundle/features.ts: the `FeatureSetDefaults` inputs (edition_defaults of every FeatureSet field and the Edition
// enum) read from the bundled descriptor.proto. They are used when a build has no descriptor.proto of its own
// (protoapi/core) and for the features a user-supplied descriptor.proto does not define.

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"

const ROOT = join(import.meta.dir, "..")
const PROTO = join(ROOT, "bundle", "proto")
const FEATURES = join(ROOT, "src", "bundle", "features.ts")

const walk = (dir: string): string[] =>
  readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const p = join(dir, name)
      return statSync(p).isDirectory() ? walk(p) : p.endsWith(".proto") ? [p] : []
    })

/** Files protoapi/core keeps: built-in options, edition features and the language feature extensions. */
const CORE = new Set([
  "google/protobuf/descriptor.proto",
  "google/protobuf/cpp_features.proto",
  "google/protobuf/java_features.proto",
  "google/protobuf/go_features.proto",
])
const files = walk(PROTO).map((f) => relative(PROTO, f).split("\\").join("/"))
const header = [
  "// Generated by scripts/gen-bundle.ts from bundle/proto (see bundle/VERSIONS.md and bundle/LICENSES). Do not edit.",
]
const core = [
  ...header,
  "// Licences: protobuf and protobuf-go BSD-3-Clause.",
  "",
  "/** The bundled files protoapi/core keeps: descriptor.proto and cpp/java/go_features.proto. */",
  "export const coreSources: Readonly<Record<string, string>> = {",
]
const all = [
  ...header,
  "// Licences: protobuf, protobuf-go and grpc-gateway BSD-3-Clause; googleapis, protovalidate and protoc-gen-validate Apache-2.0.",
  "",
  'import { coreSources } from "./core-sources"',
  "",
  "export const bundledSources: Readonly<Record<string, string>> = {",
]
for (const path of files) {
  const text = JSON.stringify(readFileSync(join(PROTO, path), "utf8"))
  if (CORE.has(path)) {
    core.push(`  ${JSON.stringify(path)}: ${text},`)
    all.push(`  ${JSON.stringify(path)}: coreSources[${JSON.stringify(path)}],`)
  } else all.push(`  ${JSON.stringify(path)}: ${text},`)
}
core.push("}", "")
all.push("}", "")
writeFileSync(join(ROOT, "src", "bundle", "core-sources.ts"), core.join("\n"))
writeFileSync(join(ROOT, "src", "bundle", "sources.ts"), all.join("\n"))
console.log(`${files.length} files (${CORE.size} in core)`)

// ---- FeatureSetDefaults -------------------------------------------------------------------------------------------

const writeFeatures = (json: string) =>
  writeFileSync(
    FEATURES,
    [
      "// Generated by scripts/gen-bundle.ts from bundle/proto/google/protobuf/descriptor.proto (see bundle/VERSIONS.md).",
      "// Do not edit. The edition_defaults of every google.protobuf.FeatureSet field and the google.protobuf.Edition enum.",
      "",
      'import type { FeatureDefaultsSource } from "../features"',
      "",
      `export const bundledFeatureDefaults: FeatureDefaultsSource = ${json}`,
      "",
    ].join("\n"),
  )
// bootstrap: the builder imports this module
if (!existsSync(FEATURES)) writeFeatures("{ editions: {}, defaults: {} }")

const { buildFromProto } = await import("../src/core")
const { featureDefaultsSource } = await import("../src/features")
const descriptor = readFileSync(join(PROTO, "google", "protobuf", "descriptor.proto"), "utf8")
const { document, issues } = buildFromProto(
  { "google/protobuf/descriptor.proto": descriptor },
  { sourceMap: false, annotations: "none" },
)
if (issues.length) throw new Error(`descriptor.proto: ${issues.map((i) => i.message).join("; ")}`)
const featureSet = document.components?.messages?.["google.protobuf.FeatureSet"]
const edition = document.components?.enums?.["google.protobuf.Edition"]
if (!featureSet || !edition) throw new Error("descriptor.proto has no FeatureSet / Edition")
const source = featureDefaultsSource(
  Object.entries(featureSet.properties).map(([name, f]) => ({ name, editionDefaults: f.options?.edition_defaults })),
  Object.entries(edition.values).map(([name, v]) => ({ name, number: v.number })),
)
writeFeatures(JSON.stringify(source, null, 2))
console.log(`${Object.keys(source.defaults).length} features`)
